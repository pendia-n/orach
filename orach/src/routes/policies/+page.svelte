	<h2>Payments and refunds</h2>
	<p>
		Orach Plus is US$7.99 per month in USD and renews until cancelled. Manage or cancel through the billing portal. Access continues through the paid period after cancellation. Historical one-time stay passes retain their original terms. Stripe
		handles payment details; Orach does not store card or wallet credentials. Eligible fiat and USDC
		methods are determined by Stripe and the merchant account. Request a satisfaction refund within
		seven days of purchase through the merchant contact shown on your Stripe receipt. Duplicate
		charges and failed delivery are refundable. Applicable consumer rights are preserved.
	</p>
	<h2>Your information</h2>
	<p>
		We store your username, hashed password, hashed recovery passcode, profile, saved plans, public
		comments and payment references. Session cookies are Secure, HttpOnly, SameSite=Lax and last
		eight days. A separate pseudonymous visitor cookie helps deduplicate city searches; search
		events determine which ten cities receive twice-monthly research. Profiles and budgets are
		private. Comments and usernames are public. Device drafts remain in your browser until cleared.
	</p>
