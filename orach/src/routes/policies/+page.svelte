	<h2>Research and prices</h2>
	<p>
		Research previews contain saved excerpts and cited summaries. They are not live confirmations.
		We preserve original amounts, currencies, quantities, inclusions and restrictions. Missing
		evidence stays missing. Individual check dates are retained when available; an unsuccessful
		fetch never makes an observation fresh.
	</p>
